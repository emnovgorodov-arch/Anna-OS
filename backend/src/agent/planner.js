function createPlan(task) {

    let plan = [];

    const text = task.toLowerCase();

    // Анализ кода и разработки
    if (
        text.includes("код") ||
        text.includes("программа") ||
        text.includes("ошибка") ||
        text.includes("разработка")
    ) {

        plan = [
            "Проанализировать задачу",
            "Определить причину проблемы",
            "Предложить решение",
            "Проверить результат"
        ];

    }

    // Поиск информации
    else if (
        text.includes("цена") ||
        text.includes("сколько") ||
        text.includes("новости") ||
        text.includes("найди")
    ) {

        plan = [
            "Определить источник информации",
            "Получить актуальные данные",
            "Проверить достоверность",
            "Сформировать ответ"
        ];

    }

    // Общая задача
    else {

        plan = [
            "Понять запрос пользователя",
            "Провести анализ",
            "Подготовить решение",
            "Предоставить результат"
        ];

    }

    return {
        task,
        steps: plan,
        created: new Date().toISOString()
    };

}

module.exports = {
    createPlan
};